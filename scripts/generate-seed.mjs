// Generates supabase/seed.sql from src/data/menu.json.
// Usage: npm run seed  (then paste the file into the Supabase SQL Editor)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const menu = JSON.parse(readFileSync(join(root, 'src/data/menu.json'), 'utf8'));

/** SQL string literal; null stays NULL. */
const str = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`);
const num = (value) => (value === null || value === undefined ? 'null' : String(value));
const arr = (values) => (values.length === 0 ? "'{}'" : `array[${values.map(str).join(', ')}]::text[]`);

const lines = [];
lines.push('-- Generated by scripts/generate-seed.mjs from src/data/menu.json. Do not edit by hand.');
lines.push('-- Safe to re-run: existing rows (matched by slug / category+name / name) are left untouched.');
lines.push('');

lines.push('insert into public.categories (slug, name_tr, name_en, sort_order) values');
lines.push(
  menu.categories
    .map((c) => `  (${str(c.slug)}, ${str(c.name_tr)}, ${str(c.name_en)}, ${num(c.sort_order)})`)
    .join(',\n') + '\non conflict (slug) do nothing;',
);
lines.push('');

lines.push(
  'insert into public.products (category_id, sort_order, name_tr, name_en, weight_g, price_single, price_menu, ingredients_tr, ingredients_en, badges, allergens) values',
);
lines.push(
  menu.products
    .map(
      (p) =>
        `  ((select id from public.categories where slug = ${str(p.category)}), ${num(p.sort_order)}, ${str(p.name_tr)}, ${str(p.name_en)}, ${num(p.weight_g)}, ${num(p.price_single)}, ${num(p.price_menu)}, ${arr(p.ingredients_tr)}, ${arr(p.ingredients_en)}, ${arr(p.badges)}, ${arr(p.allergens)})`,
    )
    .join(',\n') + '\non conflict (category_id, name_tr) do nothing;',
);
lines.push('');

// Ingredient dictionary: every distinct Turkish ingredient with the English
// term at the same position, taken from the first product that uses it.
const dictionary = new Map();
for (const p of menu.products) {
  p.ingredients_tr.forEach((tr, i) => {
    if (!dictionary.has(tr)) dictionary.set(tr, p.ingredients_en[i] ?? '');
  });
}
lines.push('insert into public.ingredients (name_tr, name_en) values');
lines.push(
  [...dictionary.entries()]
    .sort((a, b) => a[0].localeCompare(b[0], 'tr'))
    .map(([tr, en]) => `  (${str(tr)}, ${str(en)})`)
    .join(',\n') + '\non conflict (name_tr) do nothing;',
);
lines.push('');

const s = menu.settings;
lines.push('update public.settings set');
lines.push(`  business_name = ${str(s.business_name ?? '')},`);
lines.push(`  currency = ${str(s.currency ?? 'TRY')},`);
lines.push(`  menu_includes_tr = nullif(${str(s.menuIncludes_tr ?? '')}, ''),`);
lines.push(`  menu_includes_en = nullif(${str(s.menuIncludes_en ?? '')}, ''),`);
lines.push(`  notice_tr = nullif(${str(s.notice_tr ?? '')}, ''),`);
lines.push(`  notice_en = nullif(${str(s.notice_en ?? '')}, '')`);
lines.push('where id = 1;');
lines.push('');

const out = join(root, 'supabase/seed.sql');
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out}: ${menu.categories.length} categories, ${menu.products.length} products, ${dictionary.size} ingredients`);
